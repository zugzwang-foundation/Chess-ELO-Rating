def with_fixed_wording(lines: list[str]) -> list[str]:
    """Every table carries the fixed wording (ELO-7 brief): where the last line of text before a table is not it, it is
    inserted above the table."""
    out: list[str] = []
    for i, s in enumerate(lines):
        if s.startswith("|") and (i == 0 or not lines[i - 1].startswith("|")):
            text = [x for x in out if x.strip()]
            if not text or FIXED not in text[-1]:
                out += [FIXED, ""]
        out.append(s)
    return out


