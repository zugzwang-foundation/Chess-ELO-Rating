#!/usr/bin/env python3
"""E13 under Freeze 3c: the 2026 U.S. Championships; prints docs/evidence/E13_us-championship-2026-freeze-3.md.

Freeze 3c (docs/decisions/D-0015_forecast-test-reading.md) extends Freeze 3b (D-0014, part A) before any result is read:
it fixes how the pre-registered forecast test is read (the primary endpoint and its sentences, the crossed interval over
players, two secondary lines, what the pairings fix about the test), after the session's review. This script runs Freeze
3b's page script, analysis/e13_us_championships_freeze3b.py, unchanged, and adds Freeze 3c's sections to its page at fixed
places (each anchor must occur exactly once), with tools/compare_event_v3c.py; Freeze 3b's script stays a module and
check (a′) keeps comparing its manifest with D-0014's, while check (a″) (tools/checks/check_freeze3c.py) compares Freeze
3c's with D-0015's. Python standard library only.

Usage: python3 analysis/e13_us_championships_freeze3c.py > docs/evidence/E13_us-championship-2026-freeze-3.md
"""
from __future__ import annotations

import contextlib
import hashlib
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "src"))
import compare_event_v3a as v3a  # noqa: E402
import compare_event_v3b as v3b  # noqa: E402
import compare_event_v3c as v3c  # noqa: E402
import e13_us_championships_freeze3 as e13  # noqa: E402  (Freeze 3's page script, unchanged)
import e13_us_championships_freeze3b as e13b  # noqa: E402  (Freeze 3b's page script, unchanged)

OPEN, WOMEN, Y2025, PENDING = e13.OPEN, e13.WOMEN, e13.Y2025, e13.PENDING
FREEZE_RECORD = "docs/decisions/D-0015_forecast-test-reading.md"
NEW_IN_3C = ["analysis/e13_us_championships_freeze3c.py", "tools/checks/check_freeze3c.py", "tools/compare_event_v3c.py"]
FREEZE3C = sorted(e13b.FREEZE3B + NEW_IN_3C)
SCOPES = (("OPEN", "U.S. Championship"), ("WOMEN", "U.S. Women's Championship"), ("POOLED", "both events pooled"))


def freeze3c_lines() -> list[tuple[str, str]]:
    return [(f, e13.sha(f)) for f in FREEZE3C] + [(f + " (without results)", e13.e3.event_sha_without_results(f))
                                                  for f in (OPEN, WOMEN)]


def freeze3c_manifest(lines: list[tuple[str, str]] | None = None) -> str:
    lines = freeze3c_lines() if lines is None else lines
    return hashlib.sha256("".join(f"{h}  {f}\n" for f, h in lines).encode("utf-8")).hexdigest()


def sg(x: float, d: int = 4) -> str:
    return f"{x:+.{d}f}"


def iv(t: tuple) -> str:
    return f"{sg(t[0])} to {sg(t[1])}"


def lines_for(res: dict) -> list[str]:
    """D-0015's lines for one scope, as table cells."""
    m, c = res["measures"], res["crossed"]
    out = [f"{sg(m['br_d'][0])} (games {iv(m['br_d'][1])}; crossed players {iv(c['br_d'])})",
           f"{sg(m['ll_d'][0])} (games {iv(m['ll_d'][1])}; crossed players {iv(c['ll_d'])})",
           f"{sg(res['shared']['ll_d_shared'][0])} (games {iv(res['shared']['ll_d_shared'][1])})"]
    r3 = res.get("rounds_3_11")
    out.append(f"{sg(r3['br_d'][0])} (games {iv(r3['br_d'][1])}); log-loss {sg(r3['ll_d'][0])} "
               f"(games {iv(r3['ll_d'][1])}); {r3['games']} games" if r3 else "—")
    return out


def blanks(res: dict) -> dict[str, str]:
    m, c = res["measures"], res["crossed"]
    r3 = res.get("rounds_3_11")
    return {"LL_DIFF_CROSSED": iv(c["ll_d"]), "BRIER_DIFF_CROSSED": iv(c["br_d"]),
            "LL_DIFF_SHARED": f"{sg(res['shared']['ll_d_shared'][0])} (games {iv(res['shared']['ll_d_shared'][1])})",
            "R3_BRIER_DIFF": (f"{sg(r3['br_d'][0])} (games {iv(r3['br_d'][1])}; players {iv(r3['br_d'][2])})"
                              if r3 else "—"),
            "R3_LL_DIFF": (f"{sg(r3['ll_d'][0])} (games {iv(r3['ll_d'][1])}; players {iv(r3['ll_d'][2])})"
                           if r3 else "—")}


def replace_once(text: str, old: str, new: str) -> str:
    assert text.count(old) == 1, old[:80]
    return text.replace(old, new)


def main() -> int:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        e13b.main()
    page = buf.getvalue()
    rates = v3b.load_draw_rates()
    loaded = {p: v3b.load(p) for p in (Y2025, OPEN, WOMEN)}
    o, w = v3a.run(OPEN), v3a.run(WOMEN)
    done = o.complete and w.complete

    page = replace_once(page, "# E13 — The 2026 U.S. Championships under Freeze 3b:",
                        "# E13 — The 2026 U.S. Championships under Freeze 3c:")
    page = replace_once(page, "`docs/decisions/D-0014_forecast-test-and-rulings.md`, part A). Generated by "
                        "`analysis/e13_us_championships_freeze3b.py` with",
                        f"`docs/decisions/D-0014_forecast-test-and-rulings.md`, part A; its reading fixed by Freeze 3c, "
                        f"`{FREEZE_RECORD}`). Generated by `analysis/e13_us_championships_freeze3c.py`, which runs "
                        "`analysis/e13_us_championships_freeze3b.py` unchanged and adds Freeze 3c's sections with "
                        "`tools/compare_event_v3c.py`, and by Freeze 3b's script with")
    page = replace_once(page, "- **The forecast test** (R54), which depends on the results: the per-game three-outcome "
                        "log-loss and the expected-score Brier score of (a)'s and (b′)'s expectations, pre-registered in "
                        "D-0014 (section below).",
                        "- **The forecast test** (R54), which depends on the results: the per-game three-outcome "
                        "log-loss and the expected-score Brier score of (a)'s and (b′)'s expectations, pre-registered in "
                        "D-0014; read as D-0015 fixes (section below): the primary endpoint is the pooled Brier "
                        "difference with its interval over games.")

    # what the pairings fix about the test
    exp = {p: v3c.expected_if_bp_right(loaded[p][0], loaded[p][1], rates) for p in (OPEN, WOMEN)}
    add = ["### What the pairings fix about the forecast test (D-0015)", "",
           f"*{v3b.FIXED}.*", "",
           "If (b′)'s forecasts were exactly right, the test would show on average, a game, with every game played: the "
           "log-loss advantage of (b′) over (a) as frozen, and over (a) with its expectation split by (b′)'s own draw "
           "probability, so that one draw model serves both columns; and the Brier advantage, (E_a − E_b′)², which needs "
           "no draw model. The difference between the first two is what the two draw splits contribute (review finding "
           "ELO8-STAT-2): the log-loss compares draw models as well as expectations, the Brier score the expectations "
           "alone.", "",
           "| event | games | log-loss advantage, as frozen | with one draw model | of which the draw split | Brier advantage "
           "| mean draw probability, (a) | (b′) |",
           "|---|---|---|---|---|---|---|---|"]
    for name, path in (("U.S. Championship", OPEN), ("U.S. Women's Championship", WOMEN)):
        x = exp[path]
        add.append(f"| {name} | {x['games']} | {x['ll_advantage']:.4f} | {x['ll_advantage_one_draw_model']:.4f} | "
                   f"{x['ll_advantage'] - x['ll_advantage_one_draw_model']:.4f} | {x['brier_advantage']:.5f} | "
                   f"{x['draw_a']:.3f} | {x['draw_bp']:.3f} |")
    add.append("")
    page = replace_once(page, "## The check: the 2025 U.S. Championship\n", "\n".join(add) + "\n## The check: the 2025 U.S. "
                        "Championship\n")

    # the 2025 illustration of D-0015's lines
    g25 = v3c.games(loaded[Y2025][0], loaded[Y2025][1], rates)
    r25 = v3c.reading([g25])
    cells = lines_for(r25)
    add = ["Read as D-0015 fixes, on 2025's games (in sample):", "",
           "| scope | Brier (b′) − (a): the primary endpoint's measure | log-loss (b′) − (a) | log-loss with one draw model "
           "(secondary) | rounds 3–11 only (secondary) |",
           "|---|---|---|---|---|",
           f"| 2025 U.S. Championship | " + " | ".join(cells) + " |", ""]
    anchor = "## 2026 U.S. Championship and U.S. Women's Championship\n"
    page = replace_once(page, anchor, "\n".join(add) + "\n" + anchor)

    # the forecast test's reading
    reading = ["**How the test is read (D-0015, fixed before any result was read, after the session's review).**", "",
               "- **The primary endpoint** is the pooled Brier difference, (b′) − (a), with its interval over games: the "
               "Brier score compares the two expectations alone, with no draw model. It is read with one of three "
               "sentences, fixed now (d the difference, lo and hi its interval over games): interval below zero, \""
               + v3c.SENTENCES["below"].format(d="d", lo="lo", hi="hi") + "\"; above zero, \""
               + v3c.SENTENCES["above"].format(d="d", lo="lo", hi="hi") + "\"; across zero, \""
               + v3c.SENTENCES["across"].format(d="d", lo="lo", hi="hi") + "\"",
               "- **Intervals.** The interval over games is the one to read for every measure. R54's interval over "
               "players is reported as Freeze 3b computes it and labelled narrower by construction: each game counts for "
               "both its players, so it is not a test (review finding ELO8-STAT-1). The crossed interval over players, "
               "each game weighted by both its players' draws, is the players-level interval to read.",
               "- **Secondary lines, not endpoints**: the log-loss with (a)'s expectation split by (b′)'s draw "
               "probability; and every measure on rounds 3 to 11 only, the games played after Freeze 3b and D-0015 (by "
               "the schedule, rounds 1 and 2, 24 of the 132 games, were played before Freeze 3b).", ""]
    anchor = "## The blanks of the proposal's §10 (D-0012, D-0014)\n"
    if done:
        go = v3c.games(o.event, loaded[OPEN][1], rates)
        gw = v3c.games(w.event, loaded[WOMEN][1], rates)
        res = {"OPEN": v3c.reading([go]), "WOMEN": v3c.reading([gw]), "POOLED": v3c.reading([go, gw])}
        reading += ["| scope | Brier (b′) − (a) | log-loss (b′) − (a) | log-loss with one draw model (secondary) | "
                    "rounds 3–11 only (secondary) |", "|---|---|---|---|---|"]
        reading += [f"| {name} | " + " | ".join(lines_for(res[k])) + " |" for k, name in SCOPES]
        reading += ["", f"**The primary endpoint:** {res['POOLED']['primary']['sentence']}", ""]
    else:
        reading += [f"**{PENDING}.**", ""]
    page = replace_once(page, anchor, "\n".join(reading) + "\n" + anchor)

    # the blanks
    new_blanks = ["PRIMARY"] + [f"*_{k}" for k in ("LL_DIFF_CROSSED", "BRIER_DIFF_CROSSED", "LL_DIFF_SHARED",
                                                    "R3_BRIER_DIFF", "R3_LL_DIFF")]
    anchor = "## The guard and the two fields\n"
    if done:
        tb = {k: blanks(res[k]) for k, _n in SCOPES}
        bl = ["The blanks D-0015 adds:", "", f"`{{{{US26_PRIMARY}}}}`: {res['POOLED']['primary']['sentence']}", "",
              "| blank | U.S. Championship (OPEN) | U.S. Women's Championship (WOMEN) | both events pooled (POOLED) |",
              "|---|---|---|---|"]
        for k in ("LL_DIFF_CROSSED", "BRIER_DIFF_CROSSED", "LL_DIFF_SHARED", "R3_BRIER_DIFF", "R3_LL_DIFF"):
            bl.append(f"| `{{{{US26_*_{k}}}}}` | {tb['OPEN'][k]} | {tb['WOMEN'][k]} | {tb['POOLED'][k]} |")
        bl.append("")
    else:
        bl = [f"D-0015 adds, computed here once both events are complete: " + ", ".join(
            f"`{{{{US26_{b}}}}}`" for b in new_blanks) + ".", ""]
    page = replace_once(page, anchor, "\n".join(bl) + "\n" + anchor)

    # Freeze 3c's section, and the commands
    lines = freeze3c_lines()
    fz = ["## Freeze 3c (D-0015), extending Freeze 3b (D-0014)", "",
          f"Recorded in `{FREEZE_RECORD}` before any result of either event was read, and tagged `freeze-3c`. SHA-256 of "
          f"the {len(NEW_IN_3C)} files Freeze 3c adds to Freeze 3b's {len(e13b.FREEZE3B)} (listed above): "
          + ", ".join(f"`{f}`" for f in NEW_IN_3C) + ":", "", "| File | SHA-256 |", "|---|---|"]
    fz += [f"| `{f}` | `{h}` |" for f, h in lines if f in NEW_IN_3C]
    fz += ["", f"Manifest (SHA-256 of the {len(lines)} lines \"hash  file\", Freeze 3b's entries and these): "
           f"`{freeze3c_manifest(lines)}`.", "",
           "Check (a″) (`tools/checks/check_freeze3c.py`) compares this manifest with the one D-0015 records on every "
           "pull request; check (a′) still compares Freeze 3b's with D-0014's and check (a) Freeze 3a's with D-0012's.", ""]
    page = replace_once(page, "## Running the comparison after the event\n", "\n".join(fz) + "\n## Running the comparison "
                        "after the event\n")
    page = replace_once(page, ".venv/bin/python analysis/e13_us_championships_freeze3b.py > "
                        "docs/evidence/E13_us-championship-2026-freeze-3.md",
                        ".venv/bin/python analysis/e13_us_championships_freeze3c.py > "
                        "docs/evidence/E13_us-championship-2026-freeze-3.md")
    sys.stdout.write(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
