#!/usr/bin/env python3
"""E13 under Freeze 3d: the 2026 U.S. Championships; prints docs/evidence/E13_us-championship-2026-freeze-3.md.

Freeze 3d (docs/decisions/D-0016_rulings-on-elo-8-questions.md) extends Freeze 3c (D-0015) before any result is read:
ruling R66 confirms the primary endpoint (the pooled Brier difference, read with its interval over games) and orders
every log-loss line to be read with the crossed interval over players. This script runs Freeze 3c's page script,
analysis/e13_us_championships_freeze3c.py, unchanged, and adds Freeze 3d's sections to its page at fixed places (each
anchor must occur exactly once), with tools/compare_event_v3d.py; Freeze 3c's script stays a module and check (a″) keeps
comparing its manifest with D-0015's, while check (a‴) (tools/checks/check_freeze3d.py) compares Freeze 3d's with
D-0016's. Python standard library only.

Usage: python3 analysis/e13_us_championships_freeze3d.py > docs/evidence/E13_us-championship-2026-freeze-3.md
"""
from __future__ import annotations

import contextlib
import hashlib
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "src"))
import compare_event_v3a as v3a  # noqa: E402
import compare_event_v3b as v3b  # noqa: E402
import compare_event_v3c as v3c  # noqa: E402
import compare_event_v3d as v3d  # noqa: E402
import e13_us_championships_freeze3 as e13  # noqa: E402  (Freeze 3's page script, unchanged)
import e13_us_championships_freeze3c as e13c  # noqa: E402  (Freeze 3c's page script, unchanged)

OPEN, WOMEN, Y2025, PENDING = e13.OPEN, e13.WOMEN, e13.Y2025, e13.PENDING
FREEZE_RECORD = "docs/decisions/D-0016_rulings-on-elo-8-questions.md"
NEW_IN_3D = ["analysis/e13_us_championships_freeze3d.py", "tools/checks/check_freeze3d.py", "tools/compare_event_v3d.py"]
FREEZE3D = sorted(e13c.FREEZE3C + NEW_IN_3D)
SCOPES = e13c.SCOPES
NEW_BLANKS = ("LL_A_CROSSED", "LL_BP_CROSSED", "LL_DIFF_SHARED_CROSSED", "R3_LL_DIFF_CROSSED")


def freeze3d_lines() -> list[tuple[str, str]]:
    return [(f, e13.sha(f)) for f in FREEZE3D] + [(f + " (without results)", e13.e3.event_sha_without_results(f))
                                                  for f in (OPEN, WOMEN)]


def freeze3d_manifest(lines: list[tuple[str, str]] | None = None) -> str:
    lines = freeze3d_lines() if lines is None else lines
    return hashlib.sha256("".join(f"{h}  {f}\n" for f, h in lines).encode("utf-8")).hexdigest()


sg, iv = e13c.sg, e13c.iv


def cells_for(res: dict, ll: dict) -> list[str]:
    """Every log-loss line of one scope with its crossed interval over players (R66), as table cells: (a)'s and (b′)'s
    means, the difference, the difference with one draw model, and rounds 3–11's difference."""
    m, sh = res["measures"], res["shared"]
    c = ll["all"]
    r3, c3 = res.get("rounds_3_11"), ll.get("rounds_3_11")
    return [f"{m['ll_a'][0]:.4f} (crossed {c['ll_a'][0]:.4f} to {c['ll_a'][1]:.4f})",
            f"{m['ll_bp'][0]:.4f} (crossed {c['ll_bp'][0]:.4f} to {c['ll_bp'][1]:.4f})",
            f"{sg(m['ll_d'][0])} (crossed {iv(c['ll_d'])})",
            f"{sg(sh['ll_d_shared'][0])} (crossed {iv(c['ll_d_shared'])})",
            f"{sg(r3['ll_d'][0])} (crossed {iv(c3['ll_d'])})" if r3 and c3 else "—"]


def blanks(res: dict, ll: dict) -> dict[str, str]:
    c = ll["all"]
    c3 = ll.get("rounds_3_11")
    return {"LL_A_CROSSED": f"{c['ll_a'][0]:.4f} to {c['ll_a'][1]:.4f}",
            "LL_BP_CROSSED": f"{c['ll_bp'][0]:.4f} to {c['ll_bp'][1]:.4f}",
            "LL_DIFF_SHARED_CROSSED": iv(c["ll_d_shared"]),
            "R3_LL_DIFF_CROSSED": iv(c3["ll_d"]) if c3 else "—"}


replace_once = e13c.replace_once


def main() -> int:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        e13c.main()
    page = buf.getvalue()
    rates = v3b.load_draw_rates()
    loaded = {p: v3b.load(p) for p in (Y2025, OPEN, WOMEN)}
    o, w = v3a.run(OPEN), v3a.run(WOMEN)
    done = o.complete and w.complete

    page = replace_once(page, "# E13 — The 2026 U.S. Championships under Freeze 3c:",
                        "# E13 — The 2026 U.S. Championships under Freeze 3d:")
    page = replace_once(page, "its reading fixed by Freeze 3c, `docs/decisions/D-0015_forecast-test-reading.md`). "
                        "Generated by `analysis/e13_us_championships_freeze3c.py`, which runs",
                        "its reading fixed by Freeze 3c, `docs/decisions/D-0015_forecast-test-reading.md`, and confirmed, "
                        f"with every log-loss line read with the crossed interval, by Freeze 3d, `{FREEZE_RECORD}`). "
                        "Generated by `analysis/e13_us_championships_freeze3d.py`, which runs "
                        "`analysis/e13_us_championships_freeze3c.py` unchanged and adds Freeze 3d's sections with "
                        "`tools/compare_event_v3d.py`; by Freeze 3c's script, which runs")
    page = replace_once(page, "read as D-0015 fixes (section below): the primary endpoint is the pooled Brier "
                        "difference with its interval over games.",
                        "read as D-0015 fixes and D-0016 confirms (section below): the primary endpoint is the pooled "
                        "Brier difference with its interval over games, and every log-loss line is read with the crossed "
                        "interval over players (R66).")

    # the 2025 illustration of R66's reading
    g25 = v3c.games(loaded[Y2025][0], loaded[Y2025][1], rates)
    r25, ll25 = v3c.reading([g25]), v3d.log_loss_lines([g25])
    add = ["Every log-loss line with its crossed interval over players, the interval R66 reads it with, on 2025's games "
           "(in sample):", "",
           "| scope | log-loss (a), nats a game | log-loss (b′) | (b′) − (a) | (b′) − (a) with one draw model (secondary) | "
           "rounds 3–11 only, (b′) − (a) (secondary) |",
           "|---|---|---|---|---|---|",
           "| 2025 U.S. Championship | " + " | ".join(cells_for(r25, ll25)) + " |", ""]
    anchor = "## 2026 U.S. Championship and U.S. Women's Championship\n"
    page = replace_once(page, anchor, "\n".join(add) + "\n" + anchor)

    # the reading, as D-0016 confirms it
    reading = ["**How the test is read, as D-0016 confirms it (R66, fixed before any result was read).**", "",
               "- **The primary endpoint** stands as D-0015 fixes it: the pooled Brier difference, (b′) − (a), read with "
               "its interval over games and one of the three sentences above. Every other Brier line is read with its "
               "interval over games too.",
               "- **Every log-loss line is read with the crossed interval over players** (games × players: the players "
               "of each event drawn with replacement, each game weighted by the product of its two players' draws): "
               "(a)'s and (b′)'s means, their difference, the difference with one draw model and the rounds 3–11 "
               "difference. For the log-loss, which is skewed, the interval over games covered the true mean in 0.83 of "
               "the review's simulated events and the crossed interval in 0.94 (`analysis/OUTPUT_ELO8_review.md`). For "
               "the log-loss lines this replaces D-0015's \"the interval over games is the one to read for every "
               "measure\"; the interval over games is still printed beside it.",
               "- R54's interval over players stays as printed, labelled narrower by construction, not a test.", ""]
    anchor = "## The blanks of the proposal's §10 (D-0012, D-0014)\n"
    if done:
        go = v3c.games(o.event, loaded[OPEN][1], rates)
        gw = v3c.games(w.event, loaded[WOMEN][1], rates)
        res = {"OPEN": v3c.reading([go]), "WOMEN": v3c.reading([gw]), "POOLED": v3c.reading([go, gw])}
        lls = {"OPEN": v3d.log_loss_lines([go]), "WOMEN": v3d.log_loss_lines([gw]),
               "POOLED": v3d.log_loss_lines([go, gw])}
        reading += ["| scope | log-loss (a), nats a game | log-loss (b′) | (b′) − (a) | (b′) − (a) with one draw model "
                    "(secondary) | rounds 3–11 only, (b′) − (a) (secondary) |", "|---|---|---|---|---|---|"]
        reading += [f"| {name} | " + " | ".join(cells_for(res[k], lls[k])) + " |" for k, name in SCOPES]
        reading += [""]
    else:
        reading += [f"**{PENDING}.**", ""]
    page = replace_once(page, anchor, "\n".join(reading) + "\n" + anchor)

    # the blanks
    anchor = "## The guard and the two fields\n"
    if done:
        tb = {k: blanks(res[k], lls[k]) for k, _n in SCOPES}
        bl = ["The blanks D-0016 adds (R66): the crossed interval over players of every log-loss line that had none.", "",
              "| blank | U.S. Championship (OPEN) | U.S. Women's Championship (WOMEN) | both events pooled (POOLED) |",
              "|---|---|---|---|"]
        for k in NEW_BLANKS:
            bl.append(f"| `{{{{US26_*_{k}}}}}` | {tb['OPEN'][k]} | {tb['WOMEN'][k]} | {tb['POOLED'][k]} |")
        bl.append("")
    else:
        bl = ["D-0016 adds (R66), computed here once both events are complete: " + ", ".join(
            f"`{{{{US26_*_{b}}}}}`" for b in NEW_BLANKS) + ".", ""]
    page = replace_once(page, anchor, "\n".join(bl) + "\n" + anchor)

    # Freeze 3d's section, and the commands
    lines = freeze3d_lines()
    fz = ["## Freeze 3d (D-0016), extending Freeze 3c (D-0015)", "",
          f"Recorded in `{FREEZE_RECORD}` before any result of either event was read, and tagged `freeze-3d`. SHA-256 of "
          f"the {len(NEW_IN_3D)} files Freeze 3d adds to Freeze 3c's {len(e13c.FREEZE3C)} (listed above): "
          + ", ".join(f"`{f}`" for f in NEW_IN_3D) + ":", "", "| File | SHA-256 |", "|---|---|"]
    fz += [f"| `{f}` | `{h}` |" for f, h in lines if f in NEW_IN_3D]
    fz += ["", f"Manifest (SHA-256 of the {len(lines)} lines \"hash  file\", Freeze 3c's entries and these): "
           f"`{freeze3d_manifest(lines)}`.", "",
           "Check (a‴) (`tools/checks/check_freeze3d.py`) compares this manifest with the one D-0016 records on every "
           "pull request; check (a″) still compares Freeze 3c's with D-0015's, check (a′) Freeze 3b's with D-0014's and "
           "check (a) Freeze 3a's with D-0012's.", ""]
    page = replace_once(page, "## Running the comparison after the event\n", "\n".join(fz) + "\n## Running the comparison "
                        "after the event\n")
    page = replace_once(page, ".venv/bin/python analysis/e13_us_championships_freeze3c.py > "
                        "docs/evidence/E13_us-championship-2026-freeze-3.md",
                        ".venv/bin/python analysis/e13_us_championships_freeze3d.py > "
                        "docs/evidence/E13_us-championship-2026-freeze-3.md")
    sys.stdout.write(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
