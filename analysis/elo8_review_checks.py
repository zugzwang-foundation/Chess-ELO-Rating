#!/usr/bin/env python3
"""Checks of the ELO-8 review (docs/review/REDTEAM_v1_0.md, ELO-8 addendum): finding ELO8-STAT-1, the coverage of the
forecast test's intervals in a round robin, measured by simulation (slow; no data needed).

Takes the 2025 U.S. Championship's pairings and ratings (tools/events/us_championship_2025.json), draws every game's
result from column (b′)'s three-outcome forecast (Freeze 3b's tools/compare_event_v3b.py, so that (b′) is the truth), and,
in each simulated event, computes the three 95 % intervals of the mean log-loss and Brier differences, (b′) − (a): over
games and over players as Freeze 3b computes them, and crossed over players as Freeze 3c does
(tools/compare_event_v3c.py). The coverage is the share of simulated events whose interval holds the true mean, the
expectation of the difference under the truth. 200 events, seed 20261011. Python standard library only.

Usage: python3 analysis/elo8_review_checks.py > analysis/OUTPUT_ELO8_review.md
"""
from __future__ import annotations

import dataclasses
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "src"))
import compare_event_v3b as v3b  # noqa: E402  (Freeze 3b, unchanged)
import compare_event_v3c as v3c  # noqa: E402  (Freeze 3c, unchanged)

EVENTS, SEED = 200, 20261011
OUTCOMES = (1.0, 0.5, 0.0)


def truth(games: list) -> dict[str, float]:
    """The expected mean differences when (b′)'s forecasts are right."""
    ll = br = 0.0
    for g in games:
        f = g.forecast
        for p, s in zip(f.p_bp, OUTCOMES):
            ll += p * (v3b._ll(f.p_bp, s) - v3b._ll(f.p_a, s))
            br += p * ((s - f.e_bp) ** 2 - (s - f.e_a) ** 2)
    return {"ll_d": ll / len(games), "br_d": br / len(games)}


def main() -> int:
    rates = v3b.load_draw_rates()
    event, r2, *_ = v3b.load("tools/events/us_championship_2025.json")
    base = v3c.games(v3b.played_copy(event, "1/2-1/2"), r2, rates)
    true = truth(base)
    rnd = random.Random(SEED)
    hits = {(k, scheme): 0 for k in ("ll_d", "br_d") for scheme in ("games", "players", "crossed")}
    widths = {key: 0.0 for key in hits}
    for _ in range(EVENTS):
        sim = []
        for g in base:
            u, f = rnd.random(), g.forecast
            s = 1.0 if u < f.p_bp[0] else 0.5 if u < f.p_bp[0] + f.p_bp[1] else 0.0
            sim.append(dataclasses.replace(g, forecast=dataclasses.replace(f, s=s)))
        res = v3b.forecast_test([[g.forecast for g in sim]])
        cr = v3c.crossed([sim], ("ll_d", "br_d"))
        for k in ("ll_d", "br_d"):
            for scheme, (lo, hi) in (("games", res[k][1]), ("players", res[k][2]), ("crossed", cr[k])):
                hits[(k, scheme)] += lo <= true[k] <= hi
                widths[(k, scheme)] += hi - lo
    print("# The ELO-8 review's checks: the forecast test's intervals in a round robin (ELO8-STAT-1)\n")
    print("Status: generated by `analysis/elo8_review_checks.py` (no data needed; slow); do not edit by hand. Cited by "
          "`docs/review/REDTEAM_v1_0.md`, ELO-8 addendum.\n")
    print(f"{EVENTS} simulated events on the 2025 U.S. Championship's pairings and ratings ({len(base)} games), every "
          "result drawn from column (b′)'s three-outcome forecast, seed "
          f"{SEED}. The true mean differences, (b′) − (a): log-loss {true['ll_d']:+.5f}, Brier {true['br_d']:+.5f}.\n")
    print("| measure | interval | coverage of the true mean | mean width |")
    print("|---|---|---|---|")
    names = {"games": "over games (Freeze 3b)", "players": "over players (Freeze 3b, R54)",
             "crossed": "crossed over players (Freeze 3c)"}
    for k, lab in (("ll_d", "log-loss (b′) − (a)"), ("br_d", "Brier (b′) − (a)")):
        for scheme in ("games", "players", "crossed"):
            print(f"| {lab} | {names[scheme]} | {hits[(k, scheme)] / EVENTS:.2f} | {widths[(k, scheme)] / EVENTS:.4f} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
