#!/usr/bin/env python3
"""The data probe for the greats (session ELO-9, Phase 1): writes docs/research/DATA-PROBE_greats.md from
analysis/aggregates/PROBE_greats.json (analysis/probe_greats_extract.py, needs data/). Every date, count and quotation
in the page comes from the aggregate; the statuses and the reading of each period are the executor's, under the brief's
rules (FIDE's site fetched politely and cached once; no game data from a source whose terms do not allow this use; none
that needs permission is used). No player is analysed. Python standard library only; deterministic.

Usage: python3 analysis/probe_greats_report.py > docs/research/DATA-PROBE_greats.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGG = ROOT / "analysis" / "aggregates" / "PROBE_greats.json"
P: list[str] = []
p = P.append
MONTH = {f"{i:02d}": m for i, m in enumerate(("January", "February", "March", "April", "May", "June", "July", "August",
                                              "September", "October", "November", "December"), 1)}


def month(ym: str) -> str:
    return f"{MONTH[ym[5:7]]} {ym[:4]}"


def day(stamp: str) -> str:
    return f"{stamp[:4]}-{stamp[4:6]}-{stamp[6:8]}"


def main() -> int:
    a = json.loads(AGG.read_text(encoding="utf-8"))
    f, ob, others = a["fide"], a["olimpbase_lists"], a["others"]
    req = f["requests"]
    dl, dl22 = f["download_page"], f["download_page_2022"]
    top, hist, calc, hb = f["top_lists"], f["histories"], f["calculations"], f["handbook"]
    by_key = {o["key"]: o for o in others}
    pages = calc["pages"]
    first_game = next(x for x in pages if x["game_rows"])
    last_tourn = [x for x in pages if not x["game_rows"]][-1]
    p("# DATA-PROBE — the greats: what FIDE's own sources hold, and every other source, period by period")
    p("")
    p("Status: DRAFT — research record, session ELO-9, Phase 1 (the data probe; no analysis). Generated by "
      "`analysis/probe_greats_report.py` from `analysis/aggregates/PROBE_greats.json`, which "
      "`analysis/probe_greats_extract.py` writes from the pages `tools/data/fetch_probe.py` fetched once each "
      "(cached under `data/`, never committed); do not edit by hand. Licence: CC BY 4.0 (`docs/LICENSE-docs.md`); quoted "
      "third-party text remains its owners' and is reproduced for verification only.")
    p("")
    p("**The question** (ELO-9 brief, Phase 1): how far back FIDE's own sources go, and on what terms: the periodic "
      "rating lists, the top lists, per-player rating histories and per-player calculations; and every other candidate "
      "source of historical results with ratings, with its licence or terms quoted verbatim and marked usable, needs "
      "permission or unusable. None that needs permission is used. The answer is given period by period in §4.")
    p("")
    p("## 1 Method and politeness")
    p("")
    p(f"Every page was fetched once by `tools/data/fetch_probe.py` between {a['probe_requests']['first']} and "
      f"{a['probe_requests']['last']} ({a['probe_requests']['count']} requests in all, robots.txt included), cached and "
      "never fetched again; each request is logged with its URL, UTC time, status, size and SHA-256. robots.txt was "
      f"respected: ratings.fide.com and handbook.fide.com publish none ({f['robots']['ratings.fide.com']}); old.fide.com "
      f"{f['robots']['old.fide.com']}; every other host's robots.txt was read once before its first page, and a page it "
      "disallows was not fetched (one: 365Chess's terms page, §3). FIDE's hosts answered "
      f"{req['count']} of the probe's requests ("
      + ", ".join(f"{h} {n}" for h, n in sorted(req["hosts"].items()))
      + f"), {', '.join(f'{n} with HTTP {s}' for s, n in sorted(req['statuses'].items()))} (a page no longer served, "
        "§2.2), besides the handbook chapter of §2.5; FIDE refused nothing.")
    p("")
    gaps = req["gaps_under_2s"]
    if gaps:
        p(f"**A slip, recorded.** The brief asks for at least two seconds between requests to FIDE's site. {len(gaps)} "
          "gaps were shorter, because the tool was run once per page and its delay held only within one run: "
          + "; ".join(f"{g['from']} → {g['to']} at {g['at']}, {g['seconds']:.0f} s" for g in gaps)
          + ". The tool now waits for the delay after the last request the manifest records for the host, across "
            f"runs; after {gaps[-1]['at']} the manifest records no gap under two seconds.")
    else:
        p("Every request to FIDE's site came at least two seconds after the one before.")
    p("")
    p("## 2 FIDE's own sources")
    p("")
    p("### 2.1 The rating lists")
    p("")
    p(f"- **Today's download page** offers {dl['periods']} periods, {month(dl['first'])} to {month(dl['last'])} "
      f"({dl['fetched_utc']}); the project holds those standard lists on disk ({f['lists_on_disk']['count']}, "
      f"{f['lists_on_disk']['first']} to {f['lists_on_disk']['last']}).")
    py = dl22["per_year"]
    p(f"- **The page as it stood in February 2022** (the Internet Archive's copy) offered {dl22['periods']} periods, "
      f"{month(dl22['first'])} to {month(dl22['last'])}: {py['2001']} a year from 2001 to 2008, {py['2009']} in 2009, "
      f"{py['2010']} a year in 2010 and 2011, {py['2012']} in 2012 and {py['2013']} a year from 2013.")
    p(f"- **FIDE still serves the older files** under their old names (the Internet Archive records "
      f"{f['old_file_names_in_wayback']['count']} such names answered from {f['old_file_names_in_wayback']['first_year']} "
      f"to {f['old_file_names_in_wayback']['last_year']}); four were fetched:")
    p("")
    p("| list | URL | fetched (UTC) | players | columns |")
    p("|---|---|---|---|---|")
    for x in f["lists_probed"]:
        p(f"| {x['file']} | {x['url']} | {x['fetched_utc']} | {x['players']:,} | {x['columns']} |")
    p("")
    p(f"- **No list before January 2001** is offered by FIDE online: the 2022 page starts at {month(dl22['first'])}, and "
      "the Internet Archive records no older list file answered by FIDE's server.")
    p("")
    p("### 2.2 The top lists")
    p("")
    tw = top["toparc_wayback"]
    p(f"- **Today's top-lists page** shows {top['tabs']} current lists (open, women, juniors and girls in standard, "
      f"rapid and blitz) and no archive ({top['archive_periods']} periods offered; {top['fetched_utc']}).")
    p(f"- **FIDE's top-list archive** (`toparc.phtml`) is no longer served: HTTP {top['toparc_live']['status']} at "
      f"{top['toparc_live']['fetched_utc']}. The Internet Archive holds {tw['answered_200']} answered copies, "
      f"{day(tw['first_snapshot'])} to {day(tw['last_snapshot'])}; its first list (`cod=1`) is \"{tw['cod1']['title']}\".")
    p("- **So FIDE's own top lists start in July 2000**; from January 2001 any list's ranks can be computed from FIDE's "
      "full list of that date (§2.1).")
    p("")
    p("### 2.3 Per-player rating histories")
    p("")
    p("The profile page's chart (`/a_chart_data.phtml`, the request the page itself sends) returns a player's ratings by "
      "list date:")
    p("")
    p("| FIDE ID | name | list dates | first | last |")
    p("|---|---|---|---|---|")
    for pid, h in hist.items():
        p(f"| {pid} | {h['name'] or '—'} | {h['points']} | {h['first'] or '—'} | {h['last'] or '—'} |")
    p("")
    p(f"FIDE's per-player histories therefore begin with the list of {month(hist['1503014']['first'])}, whatever the "
      "player's age (one ID of an older player returned none).")
    p("")
    p("### 2.4 Per-player calculations")
    p("")
    ix = calc["index"]
    p(f"The calculations tab lists, for player {ix['player']}, {ix['standard_periods']} standard periods from "
      f"{month(ix['first'])} to {month(ix['last'])}. The calculation pages read for that player:")
    p("")
    p("| list | format | tournaments | game rows | colour marks (White / Black) |")
    p("|---|---|---|---|---|")
    for x in pages:
        p(f"| {x['list']} | {x['format']} | {x['tournaments']} | {x['game_rows']} | {x['white_marks']} / "
          f"{x['black_marks']} |")
    p("")
    p(f"Up to the list of {last_tourn['list']} a page gives each tournament's totals only: the average rating of the "
      "opponents (Rc), the player's rating (Ro), the score (w), the games (n), the change and K. From the list of "
      f"{first_game['list']} it gives every game: the opponent, the opponent's rating, the score and the colour mark. "
      "E17 found FIDE's colour marks in agreement with the broadcast archive in 98.4 % of the 2020–2026 games both "
      "record [E17]; before 2020 they cannot be checked against a legitimate source.")
    p("")
    p("### 2.5 The rating regulations in force")
    p("")
    p("FIDE's handbook online holds these versions of the rating regulations:")
    p("")
    for v in hb["live_versions"]:
        p(f"- `{v['code']}`: {v['title']}")
    p("")
    w8, w03 = hb["wayback_section8_2010s"], hb["wayback_handbook_2003"]
    p(f"Nothing earlier than 1 July 2014 is online at FIDE. The Internet Archive holds FIDE's earlier handbook: §8 of the "
      f"regulations (\"The working of the FIDE Rating System\", {w8['original']}) in {w8['snapshots']} answered copies "
      f"from {day(w8['first'])} to {day(w8['last'])}, and the handbook of the 2000s ({w03['original']}) in {w03['pages']} "
      f"answered pages from {day(w03['first'])} to {day(w03['last'])}. Version 2014 (`B022014`) was fetched once at "
      f"{hb['b022014']['fetched_utc']} for Phase 3; the older texts are to be transcribed from the archived copies, with "
      "their URLs and snapshot times, where the replay needs them.")
    p("")
    p("### 2.6 FIDE's terms")
    p("")
    p("No data-specific licence or terms for the lists, histories or calculations. The site's footer, verbatim:")
    p("")
    p(f"> {f['footer']}")
    p("")
    p("As before [V 3]: FIDE's data are analysed and never redistributed in bulk; only aggregates and differences are "
      "committed (the brief; R72).")
    p("")
    p("## 3 Every other candidate source")
    p("")
    p("| source | holds | terms, verbatim | read | status | why |")
    p("|---|---|---|---|---|---|")
    for o in others:
        q = o.get("quote")
        terms = ("“" + q + "”" + (f" ({o['translation']})" if o.get("translation") else "")) if q else "—"
        if o.get("footer_quote"):
            terms += " Footer: “" + o["footer_quote"] + "”"
        if o.get("second_quote"):
            terms += " And: “" + o["second_quote"] + "”"
        src = o.get("source")
        read = f"{src['url']}, {src['fetched_utc']}, HTTP {src['status']}" if src else "not fetched"
        if o.get("live"):
            read += f"; live page {o['live']['url']}: HTTP {o['live']['status']} at {o['live']['fetched_utc']}"
        if o.get("terms_page"):
            read += f"; terms page {o['terms_page']['url']}: {o['terms_page']['status']}"
        p(f"| {o['name']} | {o['holds']} | {terms} | {read} | **{o['status']}** | {o['why']} |")
    p("")
    lst = by_key["olimpbase_lists"]
    p(f"**OlimpBase's lists, in detail.** Its summary page ({ob['summary']['url']}) lists {ob['lists']} lists, "
      f"{ob['official_lists']} of them FIDE's official lists from {month(ob['first_official'])} to {month(ob['last'])}: "
      + ", ".join(f"{n} in the {d}" for d, n in ob["per_decade"].items())
      + f". {len(ob['supplementary'])} are supplementary lists of a few players each ("
      + "; ".join(f"{month(x['list'])}: {x['players']} players" for x in ob["supplementary"])
      + f"). Its file ({ob['file']['url']}, fetched once at {ob['file']['fetched_utc']}) holds {ob['file_rows']:,} player "
      "entries. The remarks it prints for some lists: " + "; ".join(f"{month(x['list'])}: {x['remark']}"
                                                                   for x in ob["remarks"])
      + f". Its January 2001 list has {ob['jan_2001_players']:,} players, as many as FIDE's own file of that date (§2.1); "
        "Phase 3 checks the transcription against FIDE's four lists of 2001 before using it.")
    p("")
    p(f"Status \"usable\" for the lists rests on the terms quoted: {lst['why']}. The games are another matter: the same "
      "site credits ChessBase's database and the archives of TWIC's editor among their sources, and the brief excludes "
      "both without the operator's written permission.")
    p("")
    p("## 4 Period by period")
    p("")
    dec = ob["per_decade"]
    p("| period | FIDE's rating lists | ranks 1–3, #2 and #10 | per-player histories | per-player calculations | rules in "
      "force, text | games with ratings linking eras | usable |")
    p("|---|---|---|---|---|---|---|---|")
    p(f"| 1971–1989 | not online at FIDE; OlimpBase's transcription of FIDE's official lists from July 1971 ({dec['1970s']} "
      f"lists in the 1970s, {len(ob['supplementary'])} of them supplementary, {dec['1980s']} in the 1980s) | computable from each full list; "
      "no activity flags (every listed player ranked); rating floors (untitled players under 2250 unlisted in 1971) | "
      "none at FIDE | none | not needed (no replay) | none legitimately usable | FIDE's lists as OlimpBase transcribes "
      "them, cited, for non-commercial analysis |")
    p(f"| 1990–1999 | not online at FIDE; OlimpBase's transcription, two lists a year ({dec['1990s']}); FIDE IDs from "
      "January 1990, activity flags from July 1992, ratings no longer rounded to 0 or 5 from January 1999 | computable; "
      "active players from July 1992 | none at FIDE | none | not needed | none legitimately usable | as above |")
    p(f"| 2000–2007 | FIDE's own full lists from January 2001, {py['2001']} a year (OlimpBase's for 2000); FIDE's top-100 archive "
      "from July 2000, Internet Archive copies only | computable from FIDE's lists from 2001 | from April 2003 | "
      "tournament totals only (Rc, Ro, w, n, change, K), from July 2001 | Internet Archive copies of FIDE's handbook of "
      "the 2000s | none legitimately usable (Chess-Results, from 2006, needs permission) | lists and ranks; "
      "calculations only as tournament totals |")
    p(f"| 2008–2019 | FIDE's own full lists: {py['2008']} in 2008, {py['2009']} in 2009, {py['2010']} a year in "
      f"2010–2011, {py['2012']} in 2012, {py['2013']} a year from 2013 | computable | yes | every game from the list of April 2008, with opponents' ratings and colour marks "
      "| Internet Archive copies to June 2014; FIDE's handbook online from July 2014 | none pool-wide; FIDE's "
      "calculations give each player's own games | lists, ranks, histories and per-game calculations |")
    p("")
    p("## 5 What this allows, under the brief's rules (no analysis yet)")
    p("")
    p("- **(i) FIDE's published series**: at every list date from July 1971 (OlimpBase's transcription of FIDE's lists "
      "to 2000, FIDE's own files from January 2001), aggregates only.")
    p("- **(ii) Dominance** (the gap to the list's #2 and #10): on every full list from July 1971; the supplementary "
      "lists of 1978–1980 are not full lists.")
    p(f"- **(iii) The replay under both systems**: only where FIDE's calculations give every game, from the list of "
      f"{first_game['list']}; the tournament totals of {month(ix['first'])} to {last_tourn['list']} cannot carry a "
      "per-game table.")
    p("- **(iv) The cross-era head-to-head**: not possible. No legitimately usable game data link the eras: TWIC, "
      "ChessBase, Chessmetrics, PGN Mentor, KingBase, Chessgames.com, 365Chess and Chess-Results need permission; "
      "OlimpBase's Olympiad games credit ChessBase and TWIC's editor among their sources; the Lichess broadcast archive "
      "starts in 2020; FIDE's calculations give each player's own games from 2008 only, not a pool linking eras.")
    p("")
    p("## 6 Not verified")
    p("")
    p("- OlimpBase's transcription before 2001: checked in Phase 3 against FIDE's four lists of 2001 only.")
    p("- That every player's calculations change format at the same list as the one player probed here.")
    p("- FIDE's colour marks before 2020.")
    p("- The rating regulations before 1 July 2014, until transcribed from the archived copies.")
    p("- The Kaggle contest's rules (§3).")
    sys.stdout.write("\n".join(P) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
