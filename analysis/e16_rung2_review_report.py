def pooled(cs: dict, mids, gaps) -> dict:
    """Games-weighted mean of the cells' favourite residuals, its standard error with the cells taken as independent,
    and the K-free part of the yield, the games-weighted mean of m(L) times the residual."""
    rows = [(mid, gap, cs[f"{mid}|{gap}"]) for mid in mids for gap in gaps if f"{mid}|{gap}" in cs]
    rows = [(mid, gap, c) for mid, gap, c in rows if c.get("n")]
    n = sum(c["n"] for _, _, c in rows)
    if not n:
        return {"n": 0}
    mean = sum(c["n"] * c["mean"] for _, _, c in rows) / n
    se = math.sqrt(sum((c["n"] * c["se"]) ** 2 for _, _, c in rows if c.get("se"))) / n
    return {"n": n, "mean": mean, "se": se, "rows": rows}


def band_label(mid: int) -> str:
    return r11.band_label(mid)


