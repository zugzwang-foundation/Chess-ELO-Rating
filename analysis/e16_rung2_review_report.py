def touch(r0: int, k: int, threshold: int, seed: int) -> tuple[float, float, float]:
    rnd = random.Random(seed)
    mid0 = t2.band_mid(r0)
    pw, pd, _pl = t2.probs(par, 0, mid0)                      # White's probabilities at equal strength (η inside)
    cache: dict = {}

    def expect(x: int, mid: int) -> float:
        key = (x, mid)
        if key not in cache:
            cache[key] = float(t2.published(x, mid, par))
        return cache[key]
    hits = [0, 0]
    for _ in range(RUNS):
        draws = [rnd.random() for _ in range(GAMES_A_MONTH * MONTHS)]
        for j, scaled in enumerate((False, True)):
            rating, reached, i = r0, False, 0
            for _month in range(MONTHS):
                acc = 0.0
                for _g in range(GAMES_A_MONTH):
                    white = i % 2 == 0
                    u = draws[i]
                    i += 1
                    if white:
                        s = 1.0 if u < pw else 0.5 if u < pw + pd else 0.0
                    else:
                        s = 0.0 if u < pw else 0.5 if u < pw + pd else 1.0
                    mid = t2.band_mid((rating + r0) // 2)
                    x = rating - r0 + (eta if white else -eta)
                    m = m_of("standard", mid) if scaled else 1.0
                    acc += k * m * (s - expect(x, mid))
                    if rating + acc >= threshold:
                        reached = True
                change = math.floor(abs(acc) + 0.5) * (1 if acc >= 0 else -1)
                rating += change
                if rating >= threshold:
                    reached = True
            hits[j] += reached
    return hits[0] / RUNS, hits[1] / RUNS, m_of("standard", mid0)


