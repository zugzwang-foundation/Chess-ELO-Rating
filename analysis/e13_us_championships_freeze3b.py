#!/usr/bin/env python3
"""E13 under Freeze 3b: the 2026 U.S. Championships; prints docs/evidence/E13_us-championship-2026-freeze-3.md.

Freeze 3b (docs/decisions/D-0014_forecast-test-and-rulings.md, part A) extends Freeze 3a (D-0012) before any result is
read, under the architect's rulings R54 to R57: a forecast test that depends on the results, pre-registered (R54); every
figure the pairings and the October ratings fix, printed now (R55); the PILOT rebuilt on (b′) at today's K, the PILOT on
(b) with K x m withdrawn and reported once (R56). This script runs tools/compare_event_v3b.py, which runs Freeze 3a's and
Freeze 3's tools unchanged, on the committed event files. By the operator's decision of 2026-10-09 the comparison runs
once, after the event ends: an event's tables, the forecast test and the blanks of the proposal's §10 are printed only
when both events are complete; the figures the pairings fix are printed now and stay the same whatever the results (a
game marked not played removes its term). The page lists the SHA-256 of every file the comparison depends on with
their manifest, which check (a′) (tools/checks/check_freeze3b.py) compares with the one D-0014 records; Freeze 3a's page
script, analysis/e13_us_championships_freeze3a.py, stays unchanged and is used here as a module, and check (a) keeps
comparing Freeze 3a's manifest with D-0012's. Python standard library only.

Usage: python3 analysis/e13_us_championships_freeze3b.py > docs/evidence/E13_us-championship-2026-freeze-3.md
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "src"))
import compare_event_v3a as v3a  # noqa: E402
import compare_event_v3b as v3b  # noqa: E402
import e13_us_championships_freeze3 as e13  # noqa: E402  (Freeze 3's page script, unchanged)
import e13_us_championships_freeze3a as e13a  # noqa: E402  (Freeze 3a's page script, unchanged: its list and hashes)
import set_results as sr  # noqa: E402
from layer2 import guard_v2 as gv2  # noqa: E402

OPEN, WOMEN, Y2025 = e13.OPEN, e13.WOMEN, e13.Y2025
PAGE, PENDING = e13.PAGE, e13.PENDING
FREEZE_RECORD = "docs/decisions/D-0014_forecast-test-and-rulings.md"
# Freeze 3b (D-0014, part A): Freeze 3a's files, unchanged, and the five files it adds: the tool that computes what the
# pairings fix, the PILOT on (b′) and the forecast test; the draw rates behind (a)'s three outcomes and the script that
# wrote them; this page script; and the check that enforces the freeze.
NEW_IN_3B = ["analysis/e13_us_championships_freeze3b.py", "analysis/us26_draw_rate_extract.py",
             "params/draw_rate_2026-10b.json", "tools/checks/check_freeze3b.py", "tools/compare_event_v3b.py"]
FREEZE3B = sorted(e13a.FREEZE3A + NEW_IN_3B)
BLANKS_TEST = [f"{name}" for name, _k, _s in v3b.TEST_BLANKS]


def freeze3b_lines() -> list[tuple[str, str]]:
    """(file, SHA-256) for every file Freeze 3b freezes, and the 2026 event files with their results removed."""
    return [(f, e13.sha(f)) for f in FREEZE3B] + [(f + " (without results)", e13.e3.event_sha_without_results(f))
                                                  for f in (OPEN, WOMEN)]


def freeze3b_manifest(lines: list[tuple[str, str]] | None = None) -> str:
    """SHA-256 of the lines "hash  file", one per frozen file: the value D-0014 records."""
    lines = freeze3b_lines() if lines is None else lines
    return hashlib.sha256("".join(f"{h}  {f}\n" for f, h in lines).encode("utf-8")).hexdigest()


def main_blanks(c: v3a.Comparison, t) -> dict[str, str]:
    """D-0012's blanks for one complete event, the PILOT's two now on (b′) (R56)."""
    b = v3a.blanks(c)
    b.update({"R5_GAMES": f"{t.compensated_games}", "R5_DIFF": f"{t.opponents_diff:+.2f}"})
    return b


def main() -> int:
    P = print
    rates = v3b.load_draw_rates()
    loaded = {p: v3b.load(p) for p in (Y2025, OPEN, WOMEN)}
    y, o, w = v3a.run(Y2025), v3a.run(OPEN), v3a.run(WOMEN)
    fixed = {p: v3b.fixed_by_pairings(*loaded[p]) for p in (OPEN, WOMEN)}
    pil = {p: v3b.pilot_bp(*loaded[p]) for p in (Y2025, OPEN, WOMEN)}
    P("# E13 — The 2026 U.S. Championships under Freeze 3b: columns (a), (b′), (b), (b0), the PILOT on (b′), what the "
      "pairings fix, and the forecast test\n")
    P("Status: DRAFT — not for publication; the events are in progress (Freeze 3 recorded in session ELO-6, Phase 4, "
      "`docs/decisions/D-0011_rulings-and-freeze-3.md`, part B; amended by Freeze 3a in session ELO-7, Phase 0, "
      "`docs/decisions/D-0012_pre-results-amendments.md`; extended by Freeze 3b in session ELO-8, Phase 0, "
      f"`{FREEZE_RECORD}`, part A). Generated by `analysis/e13_us_championships_freeze3b.py` with "
      "`tools/compare_event_v3b.py`, which runs `tools/compare_event_v3a.py` and `tools/compare_event_v3.py` unchanged, "
      "from the event files in `tools/events/`, `params/table_fit_2026-10b.yaml`, `params/guard_2026-10b.yaml`, "
      "`params/table_fit_2026-10.yaml`, `params/rung5_us2026.json` and `params/draw_rate_2026-10b.json`; do not edit by "
      "hand. Licence: CC BY 4.0 (`docs/LICENSE-docs.md`). For the comparison it supersedes the tables that "
      "`docs/evidence/E3_us-championship-2026.md` prints under Freeze 2.\n")
    P("## What is compared (D-0011, part B, as D-0012 and D-0014 amend it)\n")
    P("- **(a)** the event's change under FIDE's rules, computed by the ratified Layer-0 engine (`src/layer0/`, Freeze 1).")
    P("- **(b′)** rung 2 at today's K, \"v2 table and narrowed guard at today's K\", **§10's main column** (R44, R45): "
      "the table calibrated by level (`params/table_fit_2026-10b.yaml`, [E11]), the narrowed guard "
      "(`params/guard_2026-10b.yaml`, R24, [E12]) and K from the list in force, reduced under K × n ≤ 700, as Layer 0 "
      "computes it; computed only from Freeze 3's frozen table and guard and Layer 0's K, with no new parameter.")
    P("- **(b)** rung 2 v2 exactly as Freeze 3 pre-registered it (D-0011, part B): the same table and guard with each "
      "game's K multiplied by the table's printed slope ratio m(L) (R32, withdrawn by R44); reported as pre-registered "
      "and labelled.")
    P("- **(b0)** rung 2 exactly as Freeze 2 pre-registered it (`tools/compare_event.py` with "
      "`params/table_fit_2026-10.yaml`, Freeze 1): the **first pre-registration, superseded**.")
    P("- **PILOT**, printed separately: rung 5 on top of **(b′) at today's K** (R56), with the frozen rung-5 inputs "
      "(`params/rung5_us2026.json`, D-0010). The PILOT on (b), with K × m, as Freeze 3 pre-registered it, is withdrawn "
      "(R56) and reported once, in the next section, labelled superseded.")
    P("- **The forecast test** (R54), which depends on the results: the per-game three-outcome log-loss and the "
      "expected-score Brier score of (a)'s and (b′)'s expectations, pre-registered in D-0014 (section below).")
    P(f"- **A game not counted** under §5.1 as D-0013 reads it (not played, a player made no move, declared unrated) is "
      f"entered with the marker `{sr.UNPLAYED}` (R43) and excluded from every column and from the forecast test; an event "
      "is complete when every game of rounds 1–11 has a result or that marker, and §10 counts played games only.")
    P("- Nothing else: rungs 3, 4, 6 and 7, and any other column, statistic, subset or event, are not computed on the "
      "event.\n")

    P("## Fixed by the pairings and the October ratings (R55)\n")
    P(f"*{v3b.FIXED}.*\n")
    P("Per player, (b′) − (a) = K × Σ(E_a − E_b′) and (b0) − (a) likewise: the score cancels, so each is set by the "
      "pairings, the October 2026 ratings and K, all known before round 1 (review finding ELO7-STAT-1). So is the "
      "PILOT's difference, K × Σ(E_b − E_p) over a compensated junior's games against opponents who are not eligible: "
      "on (b′) at today's K (R56), and on (b) with K × m (withdrawn, reported here once, superseded). Column (b) is "
      "not set by the pairings: m multiplies the score, so (b) − (a) = C + K × Σ (m − 1) × score over the player's "
      "games, and the pairings fix only C, the value with no point scored, and C + W, the value with every game won "
      "(W = K × Σ (m − 1)); where the result falls between them waits for the results. The figures assume every game is "
      "played; a game marked not played (D-0013) removes its term, the only way results can move them. They are "
      "computed by Freeze 3a's own code on two copies of each event, every game given a placeholder result (all "
      "draws; all wins for White), which must agree exactly; no result is read. The rounded changes, the players whose "
      "rounded change differs, (b)'s blanks and the forecast test depend on the results and are not computed.\n")
    for name, path in (("U.S. Championship", OPEN), ("U.S. Women's Championship", WOMEN)):
        P(f"### {name}\n")
        P(v3b.fixed_markdown(fixed[path]))
    P(f"Per event, over the players with a game to play (*{v3b.FIXED}*):\n")
    P("| event | games | (b′): mean of \\|(b′) − (a)\\| | (b′) − (a) of largest absolute value | (b0): mean of "
      "\\|(b0) − (a)\\| | (b0) − (a) of largest absolute value | PILOT: games of a compensated junior against an opponent "
      "not eligible | PILOT on (b′): those opponents' total change minus (b′) | PILOT on (b), superseded: minus (b) |")
    P("|---|---|---|---|---|---|---|---|---|")
    for name, path in (("U.S. Championship", OPEN), ("U.S. Women's Championship", WOMEN)):
        s = v3b.fixed_summary(fixed[path])
        P(f"| {name} | {s['GAMES']} | {s['MEAN_ABS_DIFF']} | {s['MAX_DIFF']} | {s['B0_MEAN_ABS_DIFF']} | "
          f"{s['B0_MAX_DIFF']} | {s['R5_GAMES']} | {s['R5_DIFF']} | {s['B_R5_DIFF']} |")
    P(f"\n{v3b.SUPERSEDED_PILOT}: the last column, the figure Freeze 3 pre-registered as `{{{{US26_*_R5_DIFF}}}}`; "
      "§10's PILOT blanks now measure the PILOT on (b′). These are the values §10's (b′), (b0) and PILOT blanks will "
      "take if every game is played.\n")

    P("## The check: the 2025 U.S. Championship\n")
    P(f"Column (a) must equal FIDE's per-event calculation (SPEC-COMPARE §4): `tests/test_compare_event_v3.py` asserts it "
      f"for all {len(y.rows)} players against `tests/fixtures/validation/us_championship_2025.json`, the fixture of E0, and "
      "that (b0) equals Freeze 2's column (b); `tests/test_compare_event_v3a.py` asserts that (b′) is column (b) without "
      "m and that the other columns are Freeze 3's; `tests/test_compare_event_v3b.py` asserts the identities above and "
      "the forecast test's arithmetic.\n")
    P(v3a.to_markdown(y))
    d = {k: [r[k] - r["a"] for r in y.rows] for k in ("bp", "b", "b0")}
    P(f"In 2025, with the same results, rung 2 at today's K (b′) would have changed the twelve players' gains by "
      f"{min(d['bp']):+.2f} to {max(d['bp']):+.2f} points against FIDE's rules, Freeze 3's column (b) by "
      f"{min(d['b']):+.2f} to {max(d['b']):+.2f}, and Freeze 2's (b0) by {min(d['b0']):+.2f} to {max(d['b0']):+.2f}. "
      "The blanks of §10, computed on 2025's results as they will be on 2026's:\n")
    e13a.summary_table(y)
    P("")
    P(v3b.pilot_bp_markdown(pil[Y2025]))
    t25 = v3b.forecast_test([v3b.game_forecasts(loaded[Y2025][0], loaded[Y2025][1], rates)])
    P("The forecast test on 2025's games, as it will run on 2026's (in sample: the v2 table and the draw rates were fitted "
      "on broadcast games of 2023-10 to 2026-09, which include 2025's event wherever it was broadcast):\n")
    P(v3b.test_markdown({"2025 U.S. Championship": t25}))

    P("## 2026 U.S. Championship and U.S. Women's Championship\n")
    P(f"**{PENDING}.**\n")
    P("By the operator's decision of 2026-10-09, no game of either 2026 championship is processed while the event runs. "
      "The comparison runs once, after the last round (21 October; the playoff of 22 October is not part of it), on all "
      "games at once.\n")
    for name, c, path in (("U.S. Championship", o, OPEN), ("U.S. Women's Championship", w, WOMEN)):
        if c.complete:
            P(f"### {name}\n")
            P(v3a.to_markdown(c))
            P(f"### {name}, PILOT on (b′)\n")
            P(v3b.pilot_bp_markdown(pil[path]))
        else:
            P(f"- {name}: {c.counted} of {c.scheduled} games have a result, {c.unplayed} marked not played; {PENDING}.")

    P("\n## The forecast test (R54), pre-registered in D-0014\n")
    P("For every counted game of both events (D-0013): the three-outcome log-loss, −ln of the probability the forecast "
      "gave the result (nats), and the expected-score Brier score, (S − E)², of column (a)'s expectation (table 8.1.2 "
      "as FIDE applies it, Layer 0, on the October 2026 ratings) and of column (b′)'s (Freeze 3's v2 table with its "
      "narrowed guard and its colour term). Table 8.1.2 has no draw model, so (a)'s three outcomes split its expected "
      "score with the draw rate of the game's 100-point level band in the v2 table's training months, standard "
      "broadcast games of 2023-10 to 2026-09 (`params/draw_rate_2026-10b.json`, E2's construction); (b′)'s split its "
      "expectation with the v2 model's own draw probability at the game. Each game is scored from White's side. "
      "Reported: the two means and their difference (b′) − (a), a negative difference favouring (b′), with percentile "
      "bootstrap 95 % intervals (2,000 resamples, seed 20261009) over games and over players, each resampled within its "
      f"event, per event and pooled. {v3b.SMALL_SAMPLE}\n")
    mids = sorted({v3b.t2.band_mid((r[g["white"]] + r[g["black"]]) // 2) for c in (o, w)
                   for r in [{pl["fide_id"]: pl["rating"] for pl in c.event["players"]}] for g in c.event["games"]})
    P("The draw rates behind (a)'s three outcomes at the level bands of the two fields' games: "
      + "; ".join(f"{m - 50}–{m + 49}: {rates[m]:.3f}" for m in mids) + ".\n")
    if o.complete and w.complete:
        go = v3b.game_forecasts(o.event, loaded[OPEN][1], rates)
        gw = v3b.game_forecasts(w.event, loaded[WOMEN][1], rates)
        tests = {"U.S. Championship": v3b.forecast_test([go]), "U.S. Women's Championship": v3b.forecast_test([gw]),
                 "both events pooled": v3b.forecast_test([go, gw])}
        P(v3b.test_markdown(tests))
    else:
        P(f"**{PENDING}.**\n")
        tests = None

    P("## The blanks of the proposal's §10 (D-0012, D-0014)\n")
    if not (o.complete and w.complete):
        P(f"**{PENDING}.** Each blank is computed here, from the tables above, once both events are complete, over played "
          "games only: `{{US26_*_GAMES}}`, the games counted; for (b′), the main column, `{{US26_*_MEAN_ABS_DIFF}}`, "
          "`{{US26_*_MAX_DIFF}}`, `{{US26_*_N_DIFFER}}`; for (b), Freeze 3's column, `{{US26_*_B_MEAN_ABS_DIFF}}`, "
          "`{{US26_*_B_MAX_DIFF}}`, `{{US26_*_B_N_DIFFER}}`; for (b0), `{{US26_*_B0_MEAN_ABS_DIFF}}`, "
          "`{{US26_*_B0_MAX_DIFF}}`, `{{US26_*_B0_N_DIFFER}}`; for the PILOT on (b′) (R56), `{{US26_*_R5_GAMES}}` and "
          "`{{US26_*_R5_DIFF}}`; for the forecast test (R54), per event and pooled (`*` = OPEN, WOMEN, POOLED), "
          + ", ".join(f"`{{{{US26_*_{b}}}}}`" for b in BLANKS_TEST) +
          ". `{{US26_*_L0_MATCH}}` follows the 1 November 2026 list, from FIDE's published calculations, and "
          "`{{US26_READING}}` is written by hand; D-0012 and D-0014 define each.\n")
    else:
        vals = {"OPEN": main_blanks(o, pil[OPEN]), "WOMEN": main_blanks(w, pil[WOMEN])}
        P("| blank | U.S. Championship | U.S. Women's Championship |")
        P("|---|---|---|")
        for k in v3a.BLANKS:
            P(f"| `{{{{US26_*_{k}}}}}` | {vals['OPEN'][k]} | {vals['WOMEN'][k]} |")
        tb = {scope: v3b.test_blanks(tests[name]) for scope, name in
              (("OPEN", "U.S. Championship"), ("WOMEN", "U.S. Women's Championship"), ("POOLED", "both events pooled"))}
        P("\n| blank | U.S. Championship (OPEN) | U.S. Women's Championship (WOMEN) | both events pooled (POOLED) |")
        P("|---|---|---|---|")
        for b in BLANKS_TEST:
            P(f"| `{{{{US26_*_{b}}}}}` | {tb['OPEN'][b]} | {tb['WOMEN'][b]} | {tb['POOLED'][b]} |")
        P("\n`{{US26_*_L0_MATCH}}` waits for FIDE's published calculations after the 1 November 2026 list; "
          "`{{US26_READING}}` is written by hand (D-0012, D-0014).\n")

    P("## The guard and the two fields\n")
    P("| event | games | largest gap | lowest game level | pairings in the narrowed guard's region | guard binds in (b′) "
      "and (b) |")
    P("|---|---|---|---|---|---|")
    for name, c in (("U.S. Championship", o), ("U.S. Women's Championship", w)):
        r = {pl["fide_id"]: pl["rating"] for pl in c.event["players"]}
        gaps = [abs(r[g["white"]] - r[g["black"]]) for g in c.event["games"]]
        lv = [(r[g["white"]] + r[g["black"]]) / 2 for g in c.event["games"]]
        inside = sum(1 for g in c.event["games"] if gv2.in_region(r[g["white"]], r[g["black"]]))
        P(f"| {name} | {len(c.event['games'])} | {max(gaps)} | {min(lv):g} | {inside} | {c.base.guard_games} |")
    P("\nThe official pairings of all eleven rounds with the ratings of FIDE's October 2026 list, as the event files "
      "record them; no result is read. No pairing lies in the region of the guard, so in both events (b′) differs from "
      "(b0) through the v2 table only, and (b) from (b′) through m only.\n")

    P("## Freeze 3b (D-0014), extending Freeze 3a (D-0012)\n")
    P(f"Recorded in `{FREEZE_RECORD}` (part A) before any result of either event was read, and tagged `freeze-3b`. Every "
      "fit behind these numbers uses games up to 30 September 2026, a cutoff enforced in code "
      "(`analysis/e10_guard_extract.py`, `src/layer1/data.py`, `src/layer1/fit.py`); no game of either event was read. "
      f"SHA-256 of every file the comparison depends on: Freeze 3a's {len(e13a.FREEZE3A)} files, unchanged, the "
      f"{len(NEW_IN_3B)} files Freeze 3b adds ({', '.join(f'`{f}`' for f in NEW_IN_3B)}), and the two event files with "
      "their results removed:\n")
    P("| File | SHA-256 |")
    P("|---|---|")
    lines = freeze3b_lines()
    for f, h in lines:
        tail = " (without results)" if f.endswith("(without results)") else ""
        P(f"| `{f.replace(' (without results)', '')}`{tail} | `{h}` |")
    P(f"\nManifest (SHA-256 of the {len(lines)} lines \"hash  file\" above): `{freeze3b_manifest(lines)}`.\n")
    P("Check (a′) (`tools/checks/check_freeze3b.py`) recomputes this manifest on every pull request and compares it with "
      "the one D-0014 records, so a change to any of these files, or to the pairings, ratings or K of either event file, "
      "fails the check until a new decision record supersedes D-0014; check (a) still compares Freeze 3a's manifest "
      f"(`{e13a.freeze3a_manifest()}`, {len(e13a.freeze3a_lines())} entries) with D-0012's. Entering the results, or the "
      "marker for a game not counted, changes no value here. Proposal numbers drawn from history and the simulator may "
      "still change until submission, provided no event game is read (D-0011, part B).\n")

    P("## Running the comparison after the event\n")
    P(f"Enter each round's results from the official page ({PAGE}), board by board: `1-0`, `1/2-1/2` or `0-1`; "
      f"`{sr.UNPLAYED}` for a game §5.1 does not count or rate, as D-0013 reads it; `-` for no result yet. Boards 7–12 go "
      "into the women's event file. Then regenerate this page and E3 once (`tools/README.md`):\n")
    P("```")
    P(".venv/bin/python tools/set_results.py tools/events/us_championship_2026.json ROUND R1 R2 R3 R4 R5 R6")
    P(".venv/bin/python analysis/e13_us_championships_freeze3b.py > docs/evidence/E13_us-championship-2026-freeze-3.md")
    P(".venv/bin/python analysis/e3_freeze2_record.py > docs/evidence/E3_us-championship-2026.md")
    P("```")
    return 0


if __name__ == "__main__":
    sys.exit(main())
